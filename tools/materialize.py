#!/usr/bin/env python3
"""Reproducible, pin-checked overlay; never writes into either upstream."""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def replace_once(path: Path, old: str, new: str) -> None:
    source = path.read_text(encoding="utf-8")
    count = source.count(old)
    if count != 1:
        raise RuntimeError(f"{path.name}: expected one overlay anchor, found {count}: {old[:85]!r}")
    path.write_text(source.replace(old, new, 1), encoding="utf-8")


def revision(path: Path) -> str:
    return subprocess.check_output(["git", "-C", str(path), "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL).strip()


def materialize(out: Path) -> dict:
    out = out.resolve()
    build = (ROOT / "build").resolve()
    if build not in out.parents or out == build:
        raise RuntimeError("Generated source must be in a child directory of this project's build/.")
    lock = json.loads((ROOT / "upstream.lock.json").read_text())
    for name, item in lock.items():
        path = ROOT / item["path"]
        if not (path / ".git").exists():
            raise RuntimeError("Initialize direct submodules: git submodule update --init --depth 1")
        actual = revision(path)
        if actual != item["revision"]:
            raise RuntimeError(f"{name}: expected {item['revision']}, got {actual}")
        dirty = subprocess.check_output(["git", "-C", str(path), "status", "--porcelain", "--untracked-files=no"], text=True)
        if dirty:
            raise RuntimeError(f"{name}: refusing a modified upstream tree")

    fsf = ROOT / lock["fairy-stockfish"]["path"]
    stockless = ROOT / lock["stockless"]["path"]
    if out.exists():
        if not (out / ".stockless-generated").exists():
            raise RuntimeError(f"Refusing to replace an unmanaged directory: {out}")
        shutil.rmtree(out)
    shutil.copytree(fsf, out, ignore=shutil.ignore_patterns(".git", "*.o", "stockfish", "*.nnue", "__pycache__"))
    (out / ".stockless-generated").write_text("Generated by Stockless Variants tools/materialize.py\n")
    overlay = out / "src/stockless_core"
    overlay.mkdir()
    # These two policy/configuration files are copied byte-for-byte from v0.9.0.
    for name in ("config.h", "search_policy.h"):
        shutil.copy2(stockless / "src/stockless" / name, overlay / name)
    for path in (ROOT / "src/stockless_variants").glob("*.h"):
        shutil.copy2(path, overlay / path.name)

    search = out / "src/search.cpp"
    replace_once(search, '#include "search.h"\n', '#include "search.h"\n#include "stockless_core/search_policy.h"\n#include "stockless_core/variant_policy.h"\n')
    anchor = '    Move countermove = thisThread->counterMoves[pos.piece_on(prevSq)][prevSq];\n\n'
    replace_once(search, anchor, '''    // Stockless v0.9.0 node snapshot, adapted to the variant rule core.
    const auto stocklessSettings = Stockless::variant_search_settings(pos, Stockless::search_settings());
    const auto stocklessThreat = Stockless::compute_threat_signal(
      pos, depth, ss->ttPv || PvNode || depth >= 8, stocklessSettings);
    // This FSF revision has no correction-history or next-ply cutoff counter.
    // Neutral inputs are deliberate; do not invent equivalents.
    const auto stocklessBase = Stockless::prepare_search_policy(
      {0, improving, ss->inCheck, PvNode, cutNode, stocklessThreat}, stocklessSettings);

''' + anchor)
    anchor = '      // Calculate new depth for this move\n'
    replace_once(search, anchor, '''      auto stocklessPolicy = Stockless::make_prepared_move_policy(
        stocklessBase, depth, moveCount, int(beta - alpha), 0,
        ss->ttPv, captureOrPromotion, givesCheck);

''' + anchor)
    anchor = '          int lmrDepth = std::max(newDepth - reduction(improving, depth, moveCount), 0);'
    replace_once(search, anchor, anchor + '\n          lmrDepth += stocklessPolicy.pruningDepthBoost;')
    # Same-ply singular verification may have changed ttPv/depth since pruning.
    anchor = '      // Step 15. Make the move\n'
    replace_once(search, anchor, '''      stocklessPolicy = Stockless::make_prepared_move_policy(
        stocklessBase, depth, moveCount, int(beta - alpha), 0,
        ss->ttPv, captureOrPromotion, givesCheck);

''' + anchor)
    anchor = '          Depth d = std::clamp(newDepth - r, 1, newDepth + (r < -1 && moveCount <= 5 && !doubleExtension));'
    replace_once(search, anchor, '''          r = Stockless::adapted_reduction(r, stocklessPolicy.lmrAdjustment,
                                           posKey ^ make_key(move));
''' + anchor)
    anchor = '''      if (doFullDepthSearch)
      {
          value = -search<NonPV>'''
    replace_once(search, anchor, '''      if (doFullDepthSearch)
      {
          // Optional desktop forcing re-search, bounded by the native extension budget.
          if (didLMR && stocklessPolicy.reSearchDepthBonus && !doubleExtension
              && newDepth < depth && ss->doubleExtensions < 3)
          {
              newDepth = std::min(newDepth + stocklessPolicy.reSearchDepthBonus, depth);
              ++ss->doubleExtensions; // charge every extra Stockless extension
          }
          value = -search<NonPV>''')
    anchor = '        && !pos.flip_enclosed_pieces()\n'
    replace_once(search, anchor, anchor + '        && (!Stockless::hybrid_enabled() || Stockless::variant_search_policy(pos).nullMove)\n')

    version = (ROOT / "VERSION").read_text().strip()
    try:
        sha = revision(ROOT)
    except subprocess.CalledProcessError:
        sha = "uncommitted"
    dirty = bool(subprocess.check_output(["git", "-C", str(ROOT), "status", "--porcelain"], text=True))
    misc = out / "src/misc.cpp"
    identity_sha = sha[:12] + ("-dirty" if dirty and sha != "uncommitted" else "")
    replace_once(misc, 'const string Version = "";', f'const string Version = "{version} ({identity_sha})";')
    replace_once(misc, 'ss << "Fairy-Stockfish " << Version', 'ss << "Stockless Variants " << Version')
    replace_once(misc, '<< "Fabian Fichter";', '<< "Stockless Variants contributors; Stockless; Fabian Fichter and Stockfish developers";')

    from patch_protocol import apply as patch_protocol
    patch_protocol(out)
    from patch_rules import apply as patch_rules
    patch_rules(out)
    from patch_pocket_keys import apply as patch_pocket_keys
    patch_pocket_keys(out)

    # Preserve upstream copyright/license headers and visibly identify modified
    # upstream files (GPLv3 section 5(a)). Copied Stockless headers stay exact.
    modified = []
    for path in sorted((out / "src").rglob("*")):
        original = fsf / path.relative_to(out)
        if path.suffix in (".cpp", ".h") and original.is_file() and path.read_bytes() != original.read_bytes():
            path.write_text("// Modified by Stockless Variants contributors on 2026-10-26.\n"
                            "// Policy integration or correctness/input fixes; see NOTICE.STOCKLESS-VARIANTS.md.\n"
                            + path.read_text(encoding="utf-8"), encoding="utf-8")
            modified.append(path.relative_to(out).as_posix())

    manifest = {"version": version, "commit": sha, "working_tree_dirty": dirty, "upstream": lock,
                "default_evaluation": "classical", "largeboards": True,
                "all_variants": True, "status": "experimental", "modified_upstream_files": modified}
    manifest["source_files"] = {
        p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted((out / "src").rglob("*")) if p.is_file()
    }
    (out / "build-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    shutil.copy2(ROOT / "LICENSE", out / "LICENSE.STOCKLESS-VARIANTS")
    shutil.copy2(ROOT / "NOTICE.md", out / "NOTICE.STOCKLESS-VARIANTS.md")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/engine")
    args = parser.parse_args()
    result = materialize(args.output)
    print(f"Materialized Stockless Variants {result['version']} in {args.output}")
    print("Pinned FSF rules + original Stockless policy; classical evaluation; experimental.")


if __name__ == "__main__":
    main()
